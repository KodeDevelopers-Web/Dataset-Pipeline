def _load_yaml_config(path: Path) -> Dict[str, Any]:
    """Load configuration from YAML file."""
    if not yaml:
        return {}
    
    if not path.exists():
        return {}
    
    try:
        with open(path, "r", encoding="utf8") as f:
            config = yaml.safe_load(f)
            return config if config else {}
    except Exception as e:
        print(f"Warning: Failed to load config from {path}: {e}")
        return {}


def _load_env_overrides() -> Dict[str, Any]:
    """Load configuration from environment variables."""
    overrides = {}
    
    if os.getenv("PIPELINE_CACHE_DIR"):
        overrides["cache_dir"] = os.getenv("PIPELINE_CACHE_DIR")
    if os.getenv("PIPELINE_OUTPUT_DIR"):
        overrides["output_dir"] = os.getenv("PIPELINE_OUTPUT_DIR")
    if os.getenv("PIPELINE_WORKERS"):
        overrides["workers"] = int(os.getenv("PIPELINE_WORKERS"))
    if os.getenv("PIPELINE_LOG_LEVEL"):
        overrides["log_level"] = os.getenv("PIPELINE_LOG_LEVEL")
    
    return overrides


def get_config() -> Dict[str, Any]:
    """
    Get complete configuration.
    
    Merges defaults, YAML config, and environment overrides.
    
    Returns:
        Configuration dictionary
    """
    config = DEFAULT_CONFIG.copy()
    
    # Load from YAML if exists
    yaml_path = ROOT / "config.yaml"
    if yaml_path.exists() and yaml:
        yaml_config = _load_yaml_config(yaml_path)
        config.update(yaml_config)
    
    # Apply environment overrides
    env_overrides = _load_env_overrides()
    config.update(env_overrides)
    
    return config


def get_datasets_config() -> List[Dict[str, Any]]:
    """
    Get datasets configuration.
    
    Filters based on enabled/disabled settings in main config.
    
    Returns:
        List of enabled dataset configurations
    """
    config = get_config()
    enabled = set(config.get("enabled_datasets", []))
    disabled = set(config.get("disabled_datasets", []))
    
    datasets = DEFAULT_DATASETS.copy()
    
    # Filter by enabled/disabled
    if enabled:
        datasets = [d for d in datasets if d["id"] in enabled]
    
    if disabled:
        datasets = [d for d in datasets if d["id"] not in disabled]
    
    # Apply individual dataset enabled flags
    datasets = [d for d in datasets if d.get("enabled", True)]
    
    return datasets


def save_config(config: Dict[str, Any], path: Optional[Path] = None):
    """
    Save configuration to YAML file.
    
    Args:
        config: Configuration dictionary
        path: Path to save to (default: config.yaml)
    """
    if not yaml:
        raise ImportError("PyYAML not installed. Install with: pip install pyyaml")
    
    if path is None:
        path = ROOT / "config.yaml"
    
    path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(path, "w", encoding="utf8") as f:
        yaml.safe_dump(config, f, default_flow_style=False, sort_keys=False)
    
    print(f"Configuration saved to {path}")


